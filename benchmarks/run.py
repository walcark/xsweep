"""Run every benchmark example and regenerate the results reports.

Run with::

    pixi run -e dev bench

Executes each `examples/NN_*.py` script (which appends its own measurement to
`results/history.jsonl`), then rebuilds `results/TIMING.md` and
`docs/site/_static/benchmarks_history.json` from that ledger.
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

_ROOT = Path(__file__).resolve().parent
_EXAMPLES_DIR = _ROOT / "examples"
_HISTORY_PATH = _ROOT / "results" / "history.jsonl"
_TIMING_PATH = _ROOT / "results" / "TIMING.md"
_SITE_JSON_PATH = _ROOT.parent / "docs" / "site" / "_static" / "benchmarks_history.json"


def _run_examples() -> None:
    for script in sorted(_EXAMPLES_DIR.glob("[0-9]*.py")):
        print(f"=== {script.name} ===")
        subprocess.run([sys.executable, str(script)], check=True)


def _load_history() -> list[dict[str, Any]]:
    if not _HISTORY_PATH.exists():
        return []
    with _HISTORY_PATH.open() as f:
        return [json.loads(line) for line in f if line.strip()]


def _by_case(rows: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    # history.jsonl is append-only, so file order already is chronological
    # order; no re-sorting needed (a day-resolution `date` field could not
    # disambiguate multiple same-day runs anyway).
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        grouped[row["case"]].append(row)
    return grouped


def _write_timing_md(rows: list[dict[str, Any]]) -> None:
    grouped = _by_case(rows)
    lines = [
        "# Benchmark timings",
        "",
        "Generated by `benchmarks/run.py`; do not edit by hand.",
        "",
        "Wall-clock times are only meaningful compared across runs on the",
        "same `host`; they say nothing across different machines.",
        "",
        "## Current",
        "",
        "| Case | Version | Date | Host | Calls | Wall time (s) |",
        "|---|---|---|---|---|---|",
    ]
    for case in sorted(grouped):
        latest = grouped[case][-1]
        lines.append(
            f"| {case} | {latest['xsweep_version']} | {latest['date']} | "
            f"{latest['host']} | {latest['n_calls']} | "
            f"{latest['wall_time_s']:.4f} |"
        )
    lines += ["", "## History", ""]
    for case in sorted(grouped):
        lines.append(f"### {case}")
        lines.append("")
        lines.append("| Version | Date | Host | Calls | Wall time (s) |")
        lines.append("|---|---|---|---|---|")
        for row in grouped[case]:
            lines.append(
                f"| {row['xsweep_version']} | {row['date']} | {row['host']} | "
                f"{row['n_calls']} | {row['wall_time_s']:.4f} |"
            )
        lines.append("")
    _TIMING_PATH.write_text("\n".join(lines) + "\n")


def _write_site_json(rows: list[dict[str, Any]]) -> None:
    grouped = _by_case(rows)
    payload = [
        {
            "case": case,
            "points": [
                {
                    "version": row["xsweep_version"],
                    "date": row["date"],
                    "host": row["host"],
                    "n_calls": row["n_calls"],
                    "wall_time_s": row["wall_time_s"],
                }
                for row in points
            ],
        }
        for case, points in sorted(grouped.items())
    ]
    _SITE_JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    _SITE_JSON_PATH.write_text(json.dumps(payload, indent=2) + "\n")


def main() -> None:
    """Run every case, then rebuild TIMING.md and the site's history JSON."""
    _run_examples()
    rows = _load_history()
    _write_timing_md(rows)
    _write_site_json(rows)
    print(f"\nWrote {_TIMING_PATH}")
    print(f"Wrote {_SITE_JSON_PATH}")


if __name__ == "__main__":
    main()
